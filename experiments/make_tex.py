"""Export compact LaTeX versions of the key result tables (results/tables/*.tex). Run after all tables_phase*.py.
python experiments/make_tex.py"""
import os

import pandas as pd

T = "results/tables"


def write(df, name, caption):
    path = os.path.join(T, name + ".tex")
    with open(path, "w") as f:
        f.write(f"% {caption}\n% generated by experiments/make_tex.py from {name}.csv\n")
        f.write(df.to_latex(index=False, escape=True, float_format="%.2f", na_rep="--"))
    print("wrote", path)


def pm(df, col):
    return df[col].map(lambda v: f"{v:.2f}") + "±" + df[col + "_std"].map(lambda v: f"{v:.2f}")


def main():
    p = os.path.join(T, "T3_central_K.csv")
    if os.path.exists(p):
        d = pd.read_csv(p)
        d["TPR@1%"] = pm(d, "tpr@1")
        d["AUROC"] = pm(d, "auroc")
        write(d[[c for c in ["dataset", "lam", "detector", "TPR@1%", "AUROC", "n_seeds", "device"] if c in d]], "T3_central_K",
              "Phase 3 central: detectors × λ (fixed-K sensitivity; seeds 0-4)")
    p = os.path.join(T, "T4_fpr_control.csv")
    if os.path.exists(p):
        d = pd.read_csv(p)
        d = d[(d.alpha == 0.05) & d.method.isin(["feco_global", "conformal_global", "conformal_local", "robust_global"])]
        d = d[["dataset", "partition", "method", "id_mean_abs_fpr_minus_alpha_mean", "id_frac_violate_mean",
               "ref_exact_violate_id_mean", "test_mean_fpr_mean", "tpr_mean_mean", "n_seeds", "device"]]
        d.columns = ["dataset", "partition", "method", "|FPR-a| (id)", "violate (id)", "exact ref", "FPR (test)", "TPR",
                     "n", "device"]
        write(d, "T4_fpr_control_a005", "Phase 4: per-client FPR control at α=0.05")
    for name, cols in (("T5_whitelist", ["dataset", "agg", "attack", "frac", "boost", "asr_global", "asr_robust", "auroc",
                                         "tpr_conf_global_a0.05", "n_seeds", "device"]),
                       ("T5_proto", ["dataset", "frac", "K", "proto_agg", "asr_global", "auroc", "n_seeds", "device"]),
                       ("T5_calib", ["dataset", "frac", "kept_byz", "n_byz", "asr_global", "asr_robust", "asr_honest_thr",
                                     "testfpr_global_a0.05", "testfpr_robust_a0.05", "n_seeds", "device"])):
        p = os.path.join(T, name + ".csv")
        if os.path.exists(p):
            d = pd.read_csv(p)
            write(d[[c for c in cols if c in d.columns]], name, f"Phase 5: {name} (%, mean over seeds)")
    for name, keys in (("T6_central", ["dataset", "method"]), ("T6_fl", ["dataset", "partition", "method", "algo"])):
        p = os.path.join(T, name + ".csv")
        if os.path.exists(p):
            d = pd.read_csv(p)
            out = d[keys].copy()
            for c in ("auroc", "auprc", "tpr@1"):
                out[c] = pm(d, c)
            out["F1@conf0.05"] = d["f1@conf_a0.05"].map(lambda v: f"{v:.2f}")
            out["FPR@conf0.05"] = d["fpr@conf_a0.05"].map(lambda v: f"{v:.2f}")
            out["n"] = d["n_seeds"]
            out["device"] = d["device"]
            write(out, name, f"Phase 6: {name} (mean±std over seeds)")
    for name in ("T6_lofo", "T6_perdevice", "T6_latency", "T1c_loco_zeroday", "T1b_leakage_selection", "T_H1_valselected",
                 "T8_cpu_vs_gpu"):
        p = os.path.join(T, name + ".csv")
        if os.path.exists(p):
            d = pd.read_csv(p)
            d = d[[c for c in d.columns if not c.endswith("_std")]]
            write(d, name, name)


if __name__ == "__main__":
    main()
